import AppKit
import CryptoKit

public enum ClipboardPolicy {
    private static let ignoredTypeMarkers = ["Concealed", "Transient", "AutoGenerated"]

    public static func shouldIgnore(
        types: [String],
        frontmost: String?,
        excluded: Set<String>
    ) -> Bool {
        if let frontmost, !frontmost.isEmpty, excluded.contains(frontmost) {
            return true
        }
        return types.contains { type in
            ignoredTypeMarkers.contains { type.contains($0) }
        }
    }
}

public final class ClipboardMonitor {
    public var isEnabled = true
    public var excludedApps: Set<String> = []
    public var maxTextKb: UInt64 = 512
    public var maxImageMb: UInt64 = 50
    public var onError: ((String) -> Void)?

    private let client: CoreClient
    private let imagesDir: URL
    private var timer: Timer?
    private var lastChangeCount = -1
    private var isPolling = false

    public init(client: CoreClient, imagesDir: URL) {
        self.client = client
        self.imagesDir = imagesDir
    }

    public func apply(_ options: ClipboardOptions) {
        isEnabled = options.enabled
        excludedApps = Set(options.excludedApps)
        maxTextKb = options.maxTextKb
        maxImageMb = options.maxImageMb
    }

    public func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        guard isEnabled, !isPolling else { return }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let app = NSWorkspace.shared.frontmostApplication
        let bundle = app?.bundleIdentifier
        if bundle == Bundle.main.bundleIdentifier { return }
        let types = (pasteboard.types ?? []).map(\.rawValue)
        guard !ClipboardPolicy.shouldIgnore(types: types, frontmost: bundle, excluded: excludedApps) else {
            return
        }

        isPolling = true
        defer { isPolling = false }

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            let size = paths.reduce(Int64(0)) { total, path in
                let attrs = try? FileManager.default.attributesOfItem(atPath: path)
                return total + Int64((attrs?[.size] as? NSNumber)?.int64Value ?? 0)
            }
            add(kind: .file, filePaths: paths, byteSize: size, app: app)
            return
        }

        if let data = imageData(from: pasteboard) {
            guard UInt64(data.count) <= maxImageMb * 1024 * 1024 else { return }
            do {
                try FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
                let url = imagesDir.appendingPathComponent("\(Self.sha256Hex(data)).png")
                if !FileManager.default.fileExists(atPath: url.path) {
                    try data.write(to: url, options: .atomic)
                }
                add(kind: .image, imagePath: url.path, byteSize: Int64(data.count), app: app)
            } catch {
                onError?("无法保存剪贴板图片：\(error.localizedDescription)")
            }
            return
        }

        if let text = pasteboard.string(forType: .string), !text.isEmpty {
            let bytes = text.utf8.count
            guard UInt64(bytes) <= maxTextKb * 1024 else { return }
            add(kind: .text, text: text, byteSize: Int64(bytes), app: app)
        }
    }

    private func add(
        kind: ClipboardKind,
        text: String? = nil,
        filePaths: [String] = [],
        imagePath: String? = nil,
        byteSize: Int64,
        app: NSRunningApplication?
    ) {
        do {
            try client.clipboardAdd(
                kind: kind,
                text: text,
                filePaths: filePaths,
                imagePath: imagePath,
                sourceBundle: app?.bundleIdentifier,
                sourceName: app?.localizedName,
                byteSize: byteSize
            )
        } catch {
            onError?("写入剪贴板历史失败：\(error.localizedDescription)")
        }
    }

    private func imageData(from pasteboard: NSPasteboard) -> Data? {
        if let data = pasteboard.data(forType: .png) {
            return data
        }
        guard let image = NSImage(pasteboard: pasteboard),
              let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func sha256Hex(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
}
